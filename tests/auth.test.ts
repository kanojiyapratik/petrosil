/**
 * Signing in, and who may see what afterwards.
 *
 * The scoping cases matter most: one brand's staff must never read another
 * brand's clients, and a subscriber must never reach the dashboard at all.
 */
import bcrypt from "bcryptjs";
import { beforeEach, describe, expect, it } from "vitest";

import { POST as loginRoute } from "@/app/api/auth/login/route";
import { POST as logoutRoute } from "@/app/api/auth/logout/route";
import { GET as meRoute } from "@/app/api/auth/me/route";
import { GET as overviewRoute } from "@/app/api/dashboard/overview/route";

import { db } from "@/db";
import { loginAttempts, memberships, users } from "@/db/schema";
import { MAX_FAILURES } from "@/lib/auth/session";
import { hashPassword, isLegacyHash, verifyPassword } from "@/lib/auth/passwords";
import { eq } from "drizzle-orm";
import { makeBrand, resetDatabase, type Brand } from "./helpers";

/**
 * Real hashes, generated by the sites' own PHP 7.3 with
 * `password_hash($password, PASSWORD_BCRYPT)` — not reconstructed here.
 */
const LARAVEL_HASH = "$2y$10$uSig3UJl1f23F7eisTeaq.UcUflvEE0cgw8bcfl1jHhcJZKSwznYe";
const LARAVEL_PASSWORD = "correct horse battery";

let baseoil: Brand;
let bitumart: Brand;

beforeEach(async () => {
  await resetDatabase();
  baseoil = await makeBrand("baseoil", ["Singapore SN 150 FOB"]);
  bitumart = await makeBrand("bitumart", ["Bitumen Singapore Drum FOB"]);
});

async function makePerson(
  email: string,
  password: string | null,
  grants: { brand: Brand; role: string; tier?: string }[],
  options: { status?: string; hash?: string } = {},
): Promise<number> {
  const [person] = await db()
    .insert(users)
    .values({
      email,
      name: email.split("@")[0]!,
      passwordHash: options.hash ?? (password ? await hashPassword(password) : null),
      status: options.status ?? "active",
      emailVerifiedAt: new Date(),
    })
    .returning();

  for (const grant of grants) {
    await db().insert(memberships).values({
      userId: person!.id,
      siteId: grant.brand.siteId,
      role: grant.role,
      tier: grant.tier ?? "free",
    });
  }

  return person!.id;
}

function request(body: unknown, headers: Record<string, string> = {}): Request {
  return new Request("http://platform.test/api/auth/login", {
    method: "POST",
    headers: { "content-type": "application/json", ...headers },
    body: JSON.stringify(body),
  });
}

function withCookie(url: string, cookie: string, method = "GET"): Request {
  return new Request(`http://platform.test${url}`, { method, headers: { cookie } });
}

/** The Set-Cookie the login route issued, ready to send back. */
function cookieFrom(response: Response): string {
  const header = response.headers.get("set-cookie") ?? "";

  return header.split(";")[0] ?? "";
}

describe("passwords", () => {
  it("verifies a hash written by the Laravel sites", async () => {
    // This is the migration's whole premise: 112,000 people keep their password.
    expect(await verifyPassword(LARAVEL_PASSWORD, LARAVEL_HASH)).toBe(true);
    expect(await verifyPassword("wrong", LARAVEL_HASH)).toBe(false);
  });

  it("treats a $2y$ hash, and any weaker cost, as worth upgrading", async () => {
    expect(isLegacyHash(LARAVEL_HASH)).toBe(true);
    expect(isLegacyHash(await bcrypt.hash("x", 10))).toBe(true);
    expect(isLegacyHash(await hashPassword("x"))).toBe(false);
    expect(isLegacyHash(null)).toBe(false);
  });

  it("answers false for an unreadable hash rather than throwing", async () => {
    expect(await verifyPassword("x", "not-a-hash")).toBe(false);
    expect(await verifyPassword("x", "")).toBe(false);
  });
});

describe("signing in", () => {
  it("accepts a migrated subscriber and quietly re-hashes their password", async () => {
    const id = await makePerson("old@client.example", null, [{ brand: baseoil, role: "subscriber" }], {
      hash: LARAVEL_HASH,
    });

    const response = await loginRoute(
      request({ email: "old@client.example", password: LARAVEL_PASSWORD }),
    );

    expect(response.status).toBe(200);
    expect((await response.json()).user.email).toBe("old@client.example");

    const [after] = await db().select().from(users).where(eq(users.id, id));
    expect(after!.passwordHash).not.toBe(LARAVEL_HASH);
    expect(after!.passwordHash!.startsWith("$2a$12$")).toBe(true);
    // And the new hash still verifies the same password.
    expect(await verifyPassword(LARAVEL_PASSWORD, after!.passwordHash)).toBe(true);
  });

  it("is case-insensitive about the email address", async () => {
    await makePerson("Mixed@Case.example", "hunter22", [{ brand: baseoil, role: "staff" }]);

    const response = await loginRoute(request({ email: "mixed@CASE.example", password: "hunter22" }));

    expect(response.status).toBe(200);
  });

  it("says the same thing for a wrong password and an unknown account", async () => {
    await makePerson("real@client.example", "hunter22", [{ brand: baseoil, role: "subscriber" }]);

    const wrong = await loginRoute(request({ email: "real@client.example", password: "nope" }));
    const unknown = await loginRoute(request({ email: "ghost@client.example", password: "nope" }));

    expect(wrong.status).toBe(401);
    expect(unknown.status).toBe(401);
    expect(await wrong.json()).toEqual(await unknown.json());
  });

  it("refuses a disabled account", async () => {
    await makePerson("gone@client.example", "hunter22", [{ brand: baseoil, role: "subscriber" }], {
      status: "disabled",
    });

    const response = await loginRoute(request({ email: "gone@client.example", password: "hunter22" }));

    expect(response.status).toBe(401);
    expect((await response.json()).message).toContain("not active");
  });

  it("shuts the door after repeated failures, then stays shut for the right password", async () => {
    await makePerson("target@client.example", "hunter22", [{ brand: baseoil, role: "subscriber" }]);

    for (let attempt = 0; attempt < MAX_FAILURES; attempt += 1) {
      await loginRoute(request({ email: "target@client.example", password: `guess-${attempt}` }));
    }

    const throttled = await loginRoute(
      request({ email: "target@client.example", password: "hunter22" }),
    );

    expect(throttled.status).toBe(429);
    expect((await throttled.json()).message).toContain("Too many attempts");
  });

  it("records every attempt, good and bad", async () => {
    await makePerson("logged@client.example", "hunter22", [{ brand: baseoil, role: "subscriber" }]);

    await loginRoute(request({ email: "logged@client.example", password: "nope" }));
    await loginRoute(request({ email: "logged@client.example", password: "hunter22" }));

    const rows = await db().select().from(loginAttempts);
    expect(rows.map((row) => row.succeeded)).toEqual([false, true]);
    expect(rows[0]!.reason).toBe("bad_credentials");
  });
});

describe("the session", () => {
  it("identifies the signed-in person, and stops doing so after signing out", async () => {
    await makePerson("staff@petrosil.example", "hunter22", [{ brand: baseoil, role: "staff" }]);

    const login = await loginRoute(request({ email: "staff@petrosil.example", password: "hunter22" }));
    const cookie = cookieFrom(login);

    const me = await meRoute(withCookie("/api/auth/me", cookie));
    expect(me.status).toBe(200);

    const body = await me.json();
    expect(body.user.email).toBe("staff@petrosil.example");
    expect(body.is_superadmin).toBe(false);
    expect(body.memberships).toHaveLength(1);

    await logoutRoute(withCookie("/api/auth/logout", cookie, "POST"));

    // Revoked server-side: the same cookie is now worthless.
    expect((await meRoute(withCookie("/api/auth/me", cookie))).status).toBe(401);
  });

  it("refuses an invented or absent cookie", async () => {
    expect((await meRoute(new Request("http://platform.test/api/auth/me"))).status).toBe(401);
    expect(
      (await meRoute(withCookie("/api/auth/me", "petrosil_session=made-up"))).status,
    ).toBe(401);
  });
});

describe("who may open the dashboard", () => {
  it("lets a superadmin see every brand", async () => {
    await makePerson("boss@petrosil.example", "hunter22", [
      { brand: baseoil, role: "superadmin" },
      { brand: bitumart, role: "superadmin" },
    ]);

    const login = await loginRoute(request({ email: "boss@petrosil.example", password: "hunter22" }));
    const response = await overviewRoute(withCookie("/api/dashboard/overview", cookieFrom(login)));
    const body = await response.json();

    expect(response.status).toBe(200);
    expect(body.sites.map((site: { slug: string }) => site.slug)).toEqual(["baseoil", "bitumart"]);
  });

  it("shows a staff member only the brands they were granted", async () => {
    await makePerson("editor@petrosil.example", "hunter22", [{ brand: baseoil, role: "staff" }]);

    const login = await loginRoute(request({ email: "editor@petrosil.example", password: "hunter22" }));
    const response = await overviewRoute(withCookie("/api/dashboard/overview", cookieFrom(login)));
    const body = await response.json();

    expect(body.sites.map((site: { slug: string }) => site.slug)).toEqual(["baseoil"]);
    expect(body.totals.sites).toBe(1);
  });

  it("keeps a subscriber out entirely", async () => {
    await makePerson("client@company.example", "hunter22", [
      { brand: baseoil, role: "subscriber", tier: "premium" },
    ]);

    const login = await loginRoute(request({ email: "client@company.example", password: "hunter22" }));
    const response = await overviewRoute(withCookie("/api/dashboard/overview", cookieFrom(login)));

    expect(response.status).toBe(403);
    expect((await response.json()).message).toContain("Petrosil staff");
  });

  it("refuses the dashboard to anyone not signed in", async () => {
    const response = await overviewRoute(new Request("http://platform.test/api/dashboard/overview"));

    expect(response.status).toBe(401);
  });
});
